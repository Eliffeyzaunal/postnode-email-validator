def generate() -> list[dict]:
    rows: list[dict] = []
    row_number = 0
    for category, templates in CATEGORY_CASES.items():
        for index in range(40):
            row_number += 1
            provider = PROVIDERS[index % len(PROVIDERS)]
            event = dict(templates[index % len(templates)])
            if not any(key in event for key in ("event_type", "eventType", "notificationType")):
                event["event_type"] = "bounce"
            event.update({
                "event_id": f"synthetic-{row_number:04d}",
                "provider": provider,
                "recipient_hash": hashlib.sha256(f"synthetic-recipient-{row_number}".encode()).hexdigest(),
                "recipient_domain": f"{provider}.example.test",
            })
            if event.get("diagnostic_code"):
                event["diagnostic_code"] += f" trace {row_number:06d}"
            rows.append({
                "event": event,
                "expected_category": category,
                "expected_permanence": PERMANENCE[category],
                "label_source": "synthetic_specification",
                "review_status": "pending",
            })
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Anonim Görev 4 değerlendirme verisi üretir.")
    parser.add_argument("--output", type=Path, default=Path("evaluation/bounce-evaluation.jsonl"))
    parser.add_argument("--review", type=Path, default=Path("evaluation/bounce-human-review.csv"))
    args = parser.parse_args(argv)
    rows = generate()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    args.review.parent.mkdir(parents=True, exist_ok=True)
    with args.review.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "event_id", "proposed_category", "human_category", "review_status",
                "reviewer", "reviewed_at", "note",
            ],
            lineterminator="\n",
        )
        writer.writeheader()
        for row in rows:
            writer.writerow({
                "event_id": row["event"]["event_id"],
                "proposed_category": row["expected_category"],
                "human_category": "",
                "review_status": "pending",
                "reviewer": "",
                "reviewed_at": "",
                "note": "",
            })
    print(json.dumps({"dataset_size": len(rows), "output": str(args.output), "review": str(args.review)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
